import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PAGES = [("page.html", "web_page"), ("setup.html", "web_setup")]
DST = os.path.join(ROOT, "src", "webpage.c")

